function normalizedLinePointPlaneKey(node) {
  return node.nodeValue.replace(/\s+/g, " ").trim();
}

function applyLinePointPlaneText(language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);

  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (["SCRIPT", "STYLE"].includes(node.parentElement?.tagName)) continue;

    if (!originalLinePointPlaneText.has(node)) {
      originalLinePointPlaneText.set(node, node.nodeValue);
    }

    const original = originalLinePointPlaneText.get(node);
    const key = normalizedLinePointPlaneKey({ nodeValue: original });

    if (language === "eu" && linePointPlaneTextEu.has(key)) {
      const translation = linePointPlaneTextEu.get(key);
      const leadingSpace = original.match(/^\s*/)?.[0] ?? "";
      const trailingSpace = original.match(/\s*$/)?.[0] ?? "";
      node.nodeValue = `${leadingSpace}${translation}${trailingSpace}`;
    } else {
      node.nodeValue = original;
    }
  }
}

