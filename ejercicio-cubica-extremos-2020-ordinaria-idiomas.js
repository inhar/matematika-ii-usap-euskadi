function applyCubicExtrema2020Text(language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);

  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (["SCRIPT", "STYLE"].includes(node.parentElement?.tagName)) continue;

    if (!originalCubicExtrema2020Text.has(node)) {
      originalCubicExtrema2020Text.set(node, node.nodeValue);
    }

    const original = originalCubicExtrema2020Text.get(node);
    const key = original.trim();

    if (language === "eu" && cubicExtrema2020TextEu.has(key)) {
      const translation = cubicExtrema2020TextEu.get(key);
      const leadingSpace = original.match(/^\s*/)?.[0] ?? "";
      const trailingSpace = original.match(/\s*$/)?.[0] ?? "";
      node.nodeValue = `${leadingSpace}${translation}${trailingSpace}`;
    } else {
      node.nodeValue = original;
    }
  }
}

